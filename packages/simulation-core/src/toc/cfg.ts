/**
 * Context-Free Grammar (CFG) & Parsing Engine
 * Supports production rules, CYK membership algorithm, and derivations.
 */

export interface GrammarRule {
  head: string; // Non-terminal, e.g. "S"
  body: string[]; // Sequence of symbols, e.g. ["A", "B"] or ["a"]
}

export interface ContextFreeGrammar {
  variables: string[]; // Non-terminals, e.g. ["S", "A", "B"]
  terminals: string[]; // Terminals, e.g. ["a", "b"]
  startSymbol: string;
  rules: GrammarRule[];
}

export interface ParseTreeNode {
  symbol: string;
  children?: ParseTreeNode[];
}

export class CFGEngine {
  /**
   * CYK (Cocke-Younger-Kasami) algorithm for testing string membership in a Chomsky Normal Form (CNF) grammar.
   * CNF rules are either:
   * A -> BC (two non-terminals) or A -> a (single terminal).
   */
  static cykParse(
    grammar: ContextFreeGrammar,
    word: string,
  ): {
    accepted: boolean;
    table: Set<string>[][]; // Triangular parse table
  } {
    const n = word.length;
    if (n === 0) {
      // Check if start symbol derives epsilon
      const epsilonAccepted = grammar.rules.some(
        (r) => r.head === grammar.startSymbol && r.body.length === 1 && r.body[0] === 'ε',
      );
      return { accepted: epsilonAccepted, table: [] };
    }

    // table[length - 1][start_index]
    const table: Set<string>[][] = [];
    for (let l = 0; l < n; l++) {
      const row: Set<string>[] = [];
      for (let s = 0; s < n - l; s++) {
        row.push(new Set<string>());
      }
      table.push(row);
    }

    // Step 1: Base case (substrings of length 1)
    for (let i = 0; i < n; i++) {
      const char = word[i]!;
      for (const rule of grammar.rules) {
        if (rule.body.length === 1 && rule.body[0] === char) {
          table[0]![i]!.add(rule.head);
        }
      }
    }

    // Step 2: Inductive case (substrings of length 2 to n)
    for (let l = 2; l <= n; l++) {
      // span length
      for (let s = 0; s <= n - l; s++) {
        // start index
        for (let p = 1; p < l; p++) {
          // partition point
          const leftSet = table[p - 1]![s]!;
          const rightSet = table[l - p - 1]![s + p]!;

          for (const rule of grammar.rules) {
            if (rule.body.length === 2) {
              const b = rule.body[0]!;
              const c = rule.body[1]!;
              if (leftSet.has(b) && rightSet.has(c)) {
                table[l - 1]![s]!.add(rule.head);
              }
            }
          }
        }
      }
    }

    const accepted = table[n - 1]![0]!.has(grammar.startSymbol);
    return { accepted, table };
  }

  /**
   * Generates a sample Leftmost Derivation for simple CNF parse.
   */
  static generateDerivation(grammar: ContextFreeGrammar, word: string): string[] {
    const parse = this.cykParse(grammar, word);
    if (!parse.accepted) {
      return [`String "${word}" is NOT generated by this grammar.`];
    }

    return [
      `1. Start: ${grammar.startSymbol}`,
      `2. Expand start variable according to parse tree`,
      `3. Successfully derived "${word}"`,
    ];
  }
}

/**
 * Standard CNF Grammar: L = { a^n b^n | n >= 1 }
 * S -> AB | AX
 * X -> SB
 * A -> a
 * B -> b
 */
export const SAMPLE_CNF_AN_BN: ContextFreeGrammar = {
  variables: ['S', 'A', 'B', 'X'],
  terminals: ['a', 'b'],
  startSymbol: 'S',
  rules: [
    { head: 'S', body: ['A', 'B'] },
    { head: 'S', body: ['A', 'X'] },
    { head: 'X', body: ['S', 'B'] },
    { head: 'A', body: ['a'] },
    { head: 'B', body: ['b'] },
  ],
};
